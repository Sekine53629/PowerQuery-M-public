// ================================================================================
// ⓪ クエリ名：fx_正規化（関数・最初に作る）
//    文字の表記ゆれをそろえる関数。読み込んだファイルと手入力テーブルの両方で使い、
//    薬品名・列名の照合を「同じ表記」で行う
//      ・全角の英数字・記号 → 半角（Ａ→A、５→5、（→(、－→-）
//      ・半角カタカナ → 全角カタカナ（ﾃﾞｴﾋﾞｺﾞ→デエビゴ。濁点・半濁点もまとめる）
//      ・全角空白 → 半角空白、「−」（マイナス記号）→「-」、前後の空白を取る
//    1文字ずつ対応表を引くので、文字置換をくり返すより速い
//    ※ 略称は表示用に元の表記のまま残す（エリシアSで呼び出すときの表記のため）
// ================================================================================
let
    // 全角ASCII（！～～）→ 半角
    AsciiFrom = List.Transform({65281 .. 65374}, Character.FromNumber),
    AsciiTo   = List.Transform({65281 .. 65374}, each Character.FromNumber(_ - 65248)),
    // 半角カタカナ（1文字）→ 全角
    KanaFrom  = Text.ToList("｡｢｣､･ｦｧｨｩｪｫｬｭｮｯｰｱｲｳｴｵｶｷｸｹｺｻｼｽｾｿﾀﾁﾂﾃﾄﾅﾆﾇﾈﾉﾊﾋﾌﾍﾎﾏﾐﾑﾒﾓﾔﾕﾖﾗﾘﾙﾚﾛﾜﾝﾞﾟ"),
    KanaTo    = Text.ToList("。「」、・ヲァィゥェォャュョッーアイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワン゛゜"),
    Map       = Record.FromList(AsciiTo & KanaTo & {" ", "-"}, AsciiFrom & KanaFrom & {"　", "−"}),
    // 濁点・半濁点つきの半角カタカナ（2文字）→ 全角1文字。先にまとめて置き換える
    Dakuten   = List.Zip({
                    {"ｳﾞ", "ｶﾞ", "ｷﾞ", "ｸﾞ", "ｹﾞ", "ｺﾞ", "ｻﾞ", "ｼﾞ", "ｽﾞ", "ｾﾞ", "ｿﾞ", "ﾀﾞ", "ﾁﾞ", "ﾂﾞ", "ﾃﾞ", "ﾄﾞ",
                     "ﾊﾞ", "ﾋﾞ", "ﾌﾞ", "ﾍﾞ", "ﾎﾞ", "ﾊﾟ", "ﾋﾟ", "ﾌﾟ", "ﾍﾟ", "ﾎﾟ"},
                    {"ヴ", "ガ", "ギ", "グ", "ゲ", "ゴ", "ザ", "ジ", "ズ", "ゼ", "ゾ", "ダ", "ヂ", "ヅ", "デ", "ド",
                     "バ", "ビ", "ブ", "ベ", "ボ", "パ", "ピ", "プ", "ペ", "ポ"}}),
    HasHalfKana = (t as text) as logical => Text.Length(Text.Select(t, KanaFrom)) > 0,

    Fn = (v as any) as nullable text =>
        if v = null then null
        else
            let
                t0 = Text.From(v),
                t1 = if HasHalfKana(t0)
                     then List.Accumulate(Dakuten, t0, (s, p) => Text.Replace(s, p{0}, p{1}))
                     else t0,
                t2 = Text.Combine(List.Transform(Text.ToList(t1), each Record.FieldOrDefault(Map, _, _)))
            in
                Text.Trim(t2)
in
    Fn
