// ================================================================================
// ⑥ クエリ名：T_日次（データモデルに読み込む）
//    薬品使用量分析データ（実績フォルダ・③ 日次データ）を、日付×薬品の1行にまとめる
//    ・予定数量：次回来局予定から作られた数量（定期の予定。臨時・新患・飛び処方は入らない）
//    ・予定患者数：その日にその薬が予定されていた患者の数（定期分の頻度）
//    ・在庫量：その日のシートの在庫数量（発注残を含まない）
// ================================================================================
let
    Src = #"日次データ",
    Grouped = Table.Group(Src, {"日付", "薬品名"}, {
        {"予定数量",   each List.Sum([数量]), type nullable number},
        {"予定患者数", each List.Sum([患者数]), type nullable number},
        {"在庫量",     each List.Max([在庫量]), type nullable number}}),
    Result = Table.Sort(Grouped, {{"日付", Order.Ascending}, {"薬品名", Order.Ascending}})
in
    Result
